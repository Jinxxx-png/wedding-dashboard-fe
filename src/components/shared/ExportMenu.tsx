import { useState } from 'react';
import { Download, FileSpreadsheet, FileText, Loader2 } from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuRadioGroup,
  DropdownMenuRadioItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu';
import { getErrorMessage } from '@/utils/errors';
import { useAuth } from '@/contexts/AuthContext';
import type { ExportFormat } from '@/types/api';

export interface ExportDataset {
  id: string;
  label: string;
  description?: string;
}

interface ExportMenuProps {
  datasets: ExportDataset[];
  /** Performs the backend export + download; resolves with the saved filename. */
  onExport: (datasetId: string, format: ExportFormat) => Promise<string | void>;
  label?: string;
  disabled?: boolean;
  /** Shown as a hint that the current list filters are applied to the export. */
  filtersActive?: boolean;
  align?: 'start' | 'end';
}

const FORMAT_LABEL: Record<ExportFormat, string> = { xlsx: 'Excel (.xlsx)', csv: 'CSV (.csv)' };

/**
 * Reusable export dropdown. Exports are generated by the backend (authoritative, permission
 * checked); this component only forwards the request, shows progress and reports errors.
 */
export function ExportMenu({
  datasets,
  onExport,
  label = 'Export',
  disabled,
  filtersActive,
  align = 'end',
}: ExportMenuProps) {
  const { user } = useAuth();
  const preferred = user?.settings.defaultExportFormat;
  const [format, setFormat] = useState<ExportFormat>(preferred === 'csv' ? 'csv' : 'xlsx');
  const [pending, setPending] = useState(false);

  const run = async (dataset: ExportDataset, fmt: ExportFormat) => {
    if (pending) return;
    setPending(true);
    const toastId = toast.loading(`Preparing ${dataset.label.toLowerCase()} export…`);
    try {
      const filename = await onExport(dataset.id, fmt);
      toast.success('Export ready', {
        id: toastId,
        description: filename ? `Downloaded ${filename}` : `Your ${FORMAT_LABEL[fmt]} file has been downloaded.`,
      });
    } catch (error) {
      toast.error('Export failed', { id: toastId, description: getErrorMessage(error) });
    } finally {
      setPending(false);
    }
  };

  const single = datasets.length === 1 ? datasets[0] : undefined;

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button variant="outline" disabled={disabled || pending} aria-busy={pending}>
          {pending ? <Loader2 className="animate-spin" /> : <Download />}
          {pending ? 'Exporting…' : label}
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align={align} className="w-64">
        {single ? (
          <>
            <DropdownMenuLabel>{single.label}</DropdownMenuLabel>
            <DropdownMenuItem onSelect={() => run(single, 'xlsx')}>
              <FileSpreadsheet /> Download Excel (.xlsx)
            </DropdownMenuItem>
            <DropdownMenuItem onSelect={() => run(single, 'csv')}>
              <FileText /> Download CSV (.csv)
            </DropdownMenuItem>
          </>
        ) : (
          <>
            <DropdownMenuLabel>File format</DropdownMenuLabel>
            <DropdownMenuRadioGroup value={format} onValueChange={(v) => setFormat(v as ExportFormat)}>
              <DropdownMenuRadioItem value="xlsx" onSelect={(e) => e.preventDefault()}>
                Excel (.xlsx)
              </DropdownMenuRadioItem>
              <DropdownMenuRadioItem value="csv" onSelect={(e) => e.preventDefault()}>
                CSV (.csv)
              </DropdownMenuRadioItem>
            </DropdownMenuRadioGroup>
            <DropdownMenuSeparator />
            <DropdownMenuLabel>Download</DropdownMenuLabel>
            {datasets.map((d) => (
              <DropdownMenuItem key={d.id} onSelect={() => run(d, format)} className="items-start">
                {format === 'xlsx' ? <FileSpreadsheet className="mt-0.5" /> : <FileText className="mt-0.5" />}
                <div className="flex min-w-0 flex-col">
                  <span>{d.label}</span>
                  {d.description && <span className="text-xs text-muted-foreground">{d.description}</span>}
                </div>
              </DropdownMenuItem>
            ))}
          </>
        )}
        {filtersActive && (
          <>
            <DropdownMenuSeparator />
            <p className="px-2 py-1.5 text-xs text-muted-foreground">Current search and filters are applied.</p>
          </>
        )}
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
